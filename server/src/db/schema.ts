export const users = sqliteTable(
  'users',
  {
    id: integer('id').primaryKey({ autoIncrement: true }),
    role: text('role', { enum: USER_ROLES }).notNull(),
    // Compared case-insensitively (stored as typed, matched via lower()).
    username: text('username').notNull(),
    // "scrypt$N$r$p$salt$hash" — never the password itself (see lib/password.ts).
    passwordHash: text('password_hash').notNull(),
    passwordChangedAt: integer('password_changed_at', { mode: 'timestamp_ms' }).notNull(),
    // Turned-off logins cannot sign in; their history stays.
    isActive: integer('is_active', { mode: 'boolean' }).notNull().default(true),
    ...timestamps,
  },
  (t) => [
    uniqueIndex('users_username_unique').on(sql`lower(${t.username})`),
    check('users_role_valid', sql`${t.role} IN ('SUPERADMIN', 'RECEPTION', 'KITCHEN')`),
  ],
);

/** Server-side sessions. `id` is the SHA-256 of the cookie token, so a DB leak can't be replayed. */
export const sessions = sqliteTable(
  'sessions',
  {
    id: text('id').primaryKey(),
    userId: integer('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    createdAt: integer('created_at', { mode: 'timestamp_ms' }).notNull(),
    lastSeenAt: integer('last_seen_at', { mode: 'timestamp_ms' }).notNull(),
    // Sliding idle expiry, pushed forward on use; never beyond absoluteExpiresAt.
    expiresAt: integer('expires_at', { mode: 'timestamp_ms' }).notNull(),
    absoluteExpiresAt: integer('absolute_expires_at', { mode: 'timestamp_ms' }).notNull(),
  },
  (t) => [index('sessions_user_idx').on(t.userId), index('sessions_expires_idx').on(t.expiresAt)],
);

/**
 * A phone / browser that asked to be told about orders while its screen is locked or the app is in
 * the background (Web Push). Tied to the sign-in it was made with: signing out removes it, so a
 * signed-out phone gets no alerts. `endpoint` is the address of the phone maker's push service.
 */
export const pushSubscriptions = sqliteTable(
  'push_subscriptions',
  {
    id: integer('id').primaryKey({ autoIncrement: true }),
    userId: integer('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    // The sign-in this device used (a session id). Not a foreign key: it is only used to remove the device at sign-out.
    sessionId: text('session_id'),
    endpoint: text('endpoint').notNull(),
    p256dh: text('p256dh').notNull(),
    auth: text('auth').notNull(),
    userAgent: text('user_agent'),
    // Alerts stop after this unless the app is opened again (which renews it).
    expiresAt: integer('expires_at', { mode: 'timestamp_ms' }).notNull(),
    ...timestamps,
  },
  (t) => [uniqueIndex('push_subscriptions_endpoint_unique').on(t.endpoint), index('push_subscriptions_user_idx').on(t.userId)],
);
