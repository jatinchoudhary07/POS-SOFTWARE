export const orders = sqliteTable(
  'orders',
  {
    id: integer('id').primaryKey({ autoIncrement: true }),
    // Human-readable, e.g. "261021-007" = 7th order on 21 Oct 2026.
    orderNumber: text('order_number').notNull(),
    // Random id generated by the browser for each draft order. Re-sending the same
    // id (double click, network retry) returns the existing order instead of a copy.
    clientRequestId: text('client_request_id').notNull(),
    orderType: text('order_type', { enum: ORDER_TYPES }).notNull(),
    tableId: integer('table_id').references(() => diningTables.id, { onDelete: 'set null' }),
    tableNumber: text('table_number'),
    notes: text('notes'),
    // Optional: who the order is for, so staff can call them or find the order later.
    customerName: text('customer_name'),
    customerPhone: text('customer_phone'),
    // Why an order was cancelled (only set when status is CANCELLED).
    cancelReason: text('cancel_reason'),
    status: text('status', { enum: ORDER_STATUSES }).notNull().default('NEW'),
    subtotalPaise: integer('subtotal_paise').notNull(),
    ...timestamps,
  },
  (t) => [
    uniqueIndex('orders_order_number_unique').on(t.orderNumber),
    uniqueIndex('orders_client_request_id_unique').on(t.clientRequestId),
    index('orders_table_idx').on(t.tableId),
    index('orders_status_idx').on(t.status),
    index('orders_created_at_idx').on(t.createdAt),
    check('orders_subtotal_non_negative', sql`${t.subtotalPaise} >= 0`),
    check('orders_type_valid', sql`${t.orderType} IN ('DINE_IN', 'TAKEAWAY')`),
    check(
      'orders_status_valid',
      sql`${t.status} IN ('NEW', 'PREPARING', 'READY', 'COMPLETED', 'CANCELLED')`,
    ),
  ],
);

/** Remembers the request id of a submission that was merged into an existing order, so a retry never adds the items twice. */
export const mergedRequests = sqliteTable('merged_requests', {
  clientRequestId: text('client_request_id').primaryKey(),
  orderId: integer('order_id')
    .notNull()
    .references(() => orders.id, { onDelete: 'cascade' }),
  createdAt: integer('created_at', { mode: 'timestamp_ms' })
    .notNull()
    .$defaultFn(() => new Date()),
});

export const orderItems = sqliteTable(
  'order_items',
  {
    id: integer('id').primaryKey({ autoIncrement: true }),
    orderId: integer('order_id')
      .notNull()
      .references(() => orders.id, { onDelete: 'cascade' }),
    // Kept for reporting, but nullable so a menu item can be deleted later
    // without breaking old orders.
    menuItemId: integer('menu_item_id').references(() => menuItems.id, { onDelete: 'set null' }),
    // Snapshots: copied at order time so later menu edits never change old bills.
    itemName: text('item_name').notNull(),
    unitPricePaise: integer('unit_price_paise').notNull(),
    quantity: integer('quantity').notNull(),
    lineTotalPaise: integer('line_total_paise').notNull(),
    // false while the kitchen has not yet taken this line (items added to a running order stay false until then).
    kitchenDone: integer('kitchen_done', { mode: 'boolean' }).notNull().default(false),
    createdAt: timestamps.createdAt,
  },
  (t) => [
    index('order_items_order_idx').on(t.orderId),
    check('order_items_quantity_positive', sql`${t.quantity} > 0`),
    check('order_items_unit_price_non_negative', sql`${t.unitPricePaise} >= 0`),
    check(
      'order_items_line_total_matches',
      sql`${t.lineTotalPaise} = ${t.unitPricePaise} * ${t.quantity}`,
    ),
  ],
);

