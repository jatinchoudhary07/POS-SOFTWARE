export const BILL_STATUSES = ['OPEN', 'PAID', 'REFUNDED'] as const;
export type BillStatus = (typeof BILL_STATUSES)[number];
export const DISCOUNT_TYPES = ['NONE', 'PERCENT', 'AMOUNT'] as const;
export type DiscountType = (typeof DISCOUNT_TYPES)[number];

export interface TaxLine {
  name: string;
  rateBps: number;
  amountPaise: number;
}

/**
 * The bill for an order: a frozen snapshot of every number the customer sees. While OPEN it
 * can be regenerated (e.g. discount added); once PAID it never changes, so later menu, tax or
 * settings edits cannot alter a completed bill.
 */
export const bills = sqliteTable(
  'bills',
  {
    id: integer('id').primaryKey({ autoIncrement: true }),
    orderId: integer('order_id')
      .notNull()
      .references(() => orders.id, { onDelete: 'restrict' }),
    tableId: integer('table_id').references(() => diningTables.id, { onDelete: 'set null' }),
    status: text('status', { enum: BILL_STATUSES }).notNull().default('OPEN'),
    // Set when the bill/receipt was actually printed or opened for printing; cleared when the bill changes.
    printedAt: integer('printed_at', { mode: 'timestamp_ms' }),
    subtotalPaise: integer('subtotal_paise').notNull(),
    discountType: text('discount_type', { enum: DISCOUNT_TYPES }).notNull().default('NONE'),
    // PERCENT: basis points; AMOUNT: paise; NONE: 0
    discountValue: integer('discount_value').notNull().default(0),
    discountReason: text('discount_reason'),
    discountPaise: integer('discount_paise').notNull().default(0),
    taxablePaise: integer('taxable_paise').notNull(),
    taxPaise: integer('tax_paise').notNull(),
    taxLines: text('tax_lines', { mode: 'json' }).$type<TaxLine[]>().notNull(),
    roundOffPaise: integer('round_off_paise').notNull().default(0),
    totalPaise: integer('total_paise').notNull(),
    ...timestamps,
  },
  (t) => [
    uniqueIndex('bills_order_unique').on(t.orderId),
    index('bills_table_idx').on(t.tableId),
    check('bills_status_valid', sql`${t.status} IN ('OPEN', 'PAID', 'REFUNDED')`),
    check('bills_discount_type_valid', sql`${t.discountType} IN ('NONE', 'PERCENT', 'AMOUNT')`),
    check('bills_discount_range', sql`${t.discountPaise} >= 0 AND ${t.discountPaise} <= ${t.subtotalPaise}`),
    check('bills_taxable_matches', sql`${t.taxablePaise} = ${t.subtotalPaise} - ${t.discountPaise}`),
    check('bills_tax_non_negative', sql`${t.taxPaise} >= 0`),
    check('bills_total_matches', sql`${t.totalPaise} = ${t.taxablePaise} + ${t.taxPaise} + ${t.roundOffPaise}`),
    check('bills_total_non_negative', sql`${t.totalPaise} >= 0`),
  ],
);

/**
 * Links a bill to the orders it covers. For single-order bills this has one row;
 * for combined table bills it has all orders settled on that bill.
 * `uniqueIndex('bill_orders_order_unique')` prevents any order from being billed twice.
 */
export const billOrders = sqliteTable(
  'bill_orders',
  {
    id: integer('id').primaryKey({ autoIncrement: true }),
    billId: integer('bill_id')
      .notNull()
      .references(() => bills.id, { onDelete: 'cascade' }),
    orderId: integer('order_id')
      .notNull()
      .references(() => orders.id, { onDelete: 'restrict' }),
    createdAt: integer('created_at', { mode: 'timestamp_ms' })
      .notNull()
      .$defaultFn(() => new Date()),
  },
  (t) => [
    uniqueIndex('bill_orders_order_unique').on(t.orderId),
    index('bill_orders_bill_idx').on(t.billId),
    index('bill_orders_order_idx').on(t.orderId),
  ],
);

// CREDIT = the bill was put on the customer's account to be paid later (see credit_sales).
export const PAYMENT_METHODS = ['CASH', 'UPI_MANUAL', 'TERMINAL', 'CREDIT'] as const;
export type PaymentMethod = (typeof PAYMENT_METHODS)[number];

/**
 * PENDING   attempt started, waiting for a provider (future card/UPI terminal)
 * SUCCEEDED money received (cash counted / UPI verified by the cashier / terminal approved)
 * FAILED    the attempt definitely did not take money
 * UNKNOWN   outcome uncertain (e.g. terminal timed out) — must be reconciled by a person
 * REFUNDED  a SUCCEEDED payment whose money was given back (full refund)
 */
export const PAYMENT_STATUSES = ['PENDING', 'SUCCEEDED', 'FAILED', 'UNKNOWN', 'REFUNDED'] as const;
export type PaymentStatus = (typeof PAYMENT_STATUSES)[number];

/** One row per payment ATTEMPT. Rows are never deleted, so the table is an audit log. */
export const payments = sqliteTable(
  'payments',
  {
    id: integer('id').primaryKey({ autoIncrement: true }),
    orderId: integer('order_id')
      .notNull()
      .references(() => orders.id, { onDelete: 'restrict' }),
    billId: integer('bill_id')
      .notNull()
      .references(() => bills.id, { onDelete: 'restrict' }),
    method: text('method', { enum: PAYMENT_METHODS }).notNull(),
    status: text('status', { enum: PAYMENT_STATUSES }).notNull(),
    amountPaise: integer('amount_paise').notNull(),
    // Cash only: what the customer handed over, and the change returned.
    tenderedPaise: integer('tendered_paise'),
    changePaise: integer('change_paise'),
    // Sent by the client for every attempt; repeating it returns the same attempt.
    idempotencyKey: text('idempotency_key').notNull(),
    // 'MANUAL' for cash / manually verified UPI; a provider id (e.g. a terminal) otherwise.
    provider: text('provider').notNull(),
    // UPI transaction ref (UTR) typed by the cashier, or a terminal's transaction id.
    providerReference: text('provider_reference'),
    failureReason: text('failure_reason'),
    note: text('note'),
    completedAt: integer('completed_at', { mode: 'timestamp_ms' }),
    refundedAt: integer('refunded_at', { mode: 'timestamp_ms' }),
    refundReason: text('refund_reason'),
    ...timestamps,
  },
  (t) => [
    uniqueIndex('payments_idempotency_key_unique').on(t.idempotencyKey),
    // The database itself refuses a second successful payment for the same order...
    uniqueIndex('payments_one_success_per_order').on(t.orderId).where(sql`status = 'SUCCEEDED'`),
    // ...and a second attempt while one is in progress or uncertain.
    uniqueIndex('payments_one_open_attempt_per_order').on(t.orderId).where(sql`status IN ('PENDING', 'UNKNOWN')`),
    index('payments_order_idx').on(t.orderId),
    index('payments_completed_at_idx').on(t.completedAt),
    check('payments_method_valid', sql`${t.method} IN ('CASH', 'UPI_MANUAL', 'TERMINAL', 'CREDIT')`),
    check('payments_status_valid', sql`${t.status} IN ('PENDING', 'SUCCEEDED', 'FAILED', 'UNKNOWN', 'REFUNDED')`),
    check('payments_amount_positive', sql`${t.amountPaise} > 0`),
    check(
      'payments_cash_fields',
      sql`(${t.tenderedPaise} IS NULL AND ${t.changePaise} IS NULL) OR (${t.tenderedPaise} >= ${t.amountPaise} AND ${t.changePaise} = ${t.tenderedPaise} - ${t.amountPaise})`,
    ),
  ],
);

